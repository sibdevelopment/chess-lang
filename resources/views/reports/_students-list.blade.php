@php
  $studentIndexRoute = $routePrefix === 'student' ? 'student.reports' : $routePrefix.'.reports.students.index';
  $studentListAction = $studentListAction ?? route($studentIndexRoute);
  $studentResetUrl = $studentResetUrl ?? route($studentIndexRoute);
  $embeddedStudentTab = $embeddedStudentTab ?? false;
  $dateFrom = $dateFrom ?? '';
  $dateTo = $dateTo ?? '';
  $reportStatusTab = $reportStatusTab ?? 'saved';
  $canCreateReports = $canCreateReports ?? false;
  $savedReportCount = $savedReportCount ?? 0;
  $needAssessmentCount = $needAssessmentCount ?? 0;

  $filterQuery = array_filter([
    'tab' => $embeddedStudentTab ? 'student' : null,
    'search' => $studentSearch,
    'date_from' => $dateFrom,
    'date_to' => $dateTo,
  ], fn ($value) => $value !== null && $value !== '');

  $reportTabs = [
    [
      'label' => 'Saved Reports',
      'count' => $savedReportCount,
      'href' => $studentListAction.'?'.http_build_query(array_merge($filterQuery, ['status' => 'saved'])),
      'active' => $reportStatusTab === 'saved',
    ],
  ];

  if ($canCreateReports) {
    $reportTabs[] = [
      'label' => 'Need Assessment',
      'count' => $needAssessmentCount,
      'href' => $studentListAction.'?'.http_build_query(array_merge($filterQuery, ['status' => 'need_assessment'])),
      'active' => $reportStatusTab === 'need_assessment',
    ];
  }
@endphp

<div class="grid gap-6">
  <x-ui.tabs :items="$reportTabs" aria-label="Student report status" class="ui-section-tabs" />

  <div class="ui-card">
    <form method="GET" action="{{ $studentListAction }}" class="ui-report-filters">
      @if($embeddedStudentTab)
        <input type="hidden" name="tab" value="student">
      @endif
      <input type="hidden" name="status" value="{{ $reportStatusTab }}">
      <label class="ui-field">
        <span class="ui-label">Search Student</span>
        <x-ui.search name="search" :value="$studentSearch" placeholder="Search by name, username, or country" />
      </label>
      <label class="ui-field">
        <span class="ui-label">Period From</span>
        <input
          type="date"
          name="date_from"
          value="{{ $dateFrom }}"
          class="ui-input"
        >
      </label>
      <label class="ui-field">
        <span class="ui-label">Period To</span>
        <input
          type="date"
          name="date_to"
          value="{{ $dateTo }}"
          class="ui-input"
        >
      </label>
      <div class="ui-report-filter-actions">
        <x-ui.button type="submit">Apply</x-ui.button>
        @if($studentSearch !== '' || $dateFrom !== '' || $dateTo !== '')
          <x-ui.button :href="$studentResetUrl.'?'.http_build_query(array_filter(['tab' => $embeddedStudentTab ? 'student' : null, 'status' => $reportStatusTab]))" variant="secondary">Reset</x-ui.button>
        @endif
      </div>
    </form>
  </div>

  @if($reportStatusTab === 'saved')
    @if($savedReports->isEmpty())
      <x-ui.empty-state
        title="No saved reports found"
        description="Saved reports generated by a Super Admin or Coach will appear here. Select a period to view reports for that exact period."
      />
    @else
      <x-ui.table>
        <x-slot:head>
          <tr>
            <th>Student</th>
            <th>Current Batch</th>
            <th>Coach</th>
            <th>Report Period</th>
            <th>Saved On</th>
            <th>Generated By</th>
            <th>Score</th>
            <th class="text-right">Actions</th>
          </tr>
        </x-slot:head>

        @foreach($savedReports as $assessment)
          @php
            $savedStudent = $assessment->student;
            $displayGroups = $savedStudent->groups->where('is_active', true);
            if ($displayGroups->isEmpty()) {
                $displayGroups = $savedStudent->groups;
            }

            $viewUrl = $routePrefix === 'student'
                ? route('student.reports.saved.show', $assessment)
                : route($routePrefix.'.reports.students.saved.show', [$savedStudent, $assessment]);
            $pdfUrl = $routePrefix === 'student'
                ? route('student.reports.saved.pdf', $assessment)
                : route($routePrefix.'.reports.students.saved.pdf', [$savedStudent, $assessment]);
            $assessorRole = $assessment->assessor_role ?: $assessment->assessor?->role;
          @endphp
          <tr>
            <td>
              <div class="grid gap-1">
                <div class="font-semibold text-slate-900">{{ $savedStudent->name }}</div>
                <div class="text-xs font-medium text-slate-500">{{ $savedStudent->username }}</div>
              </div>
            </td>
            <td>{{ $displayGroups->pluck('name')->filter()->unique()->join(', ') ?: '—' }}</td>
            <td>{{ $displayGroups->pluck('coach.name')->filter()->unique()->join(', ') ?: '—' }}</td>
            <td>
              @if($assessment->period_start && $assessment->period_end)
                <span class="font-medium text-slate-900">{{ $assessment->period_start->format('d M Y') }}</span>
                <span class="block text-xs text-slate-500">to {{ $assessment->period_end->format('d M Y') }}</span>
              @else
                <span class="text-slate-500">Legacy - all time</span>
              @endif
            </td>
            <td>{{ $assessment->assessed_at?->timezone(config('app.timezone'))->format('d M Y, h:i A') ?: '—' }}</td>
            <td>
              <div class="grid gap-1">
                <span class="font-medium text-slate-900">{{ $assessment->assessor?->name ?? 'Archer Academy' }}</span>
                <span class="text-xs text-slate-500">{{ $assessorRole === 'admin' ? 'Super Admin' : ($assessorRole ? ucwords(str_replace('_', ' ', $assessorRole)) : '—') }}</span>
              </div>
            </td>
            <td><x-ui.badge :label="number_format((float) $assessment->percentage, 0).'% ('.$assessment->total_marks.'/100)'" variant="success" /></td>
            <td class="text-right">
              <div class="flex justify-end gap-2">
                <x-ui.button :href="$viewUrl" size="sm">View Report</x-ui.button>
                <x-ui.button :href="$pdfUrl" variant="secondary" size="sm">Download PDF</x-ui.button>
              </div>
            </td>
          </tr>
        @endforeach
      </x-ui.table>

      <div class="pt-4">
        {{ $savedReports->links('components.ui.pagination') }}
      </div>
    @endif
  @else
    @if($students->isEmpty())
      <x-ui.empty-state
        title="No assessments needed"
        description="Every matching student already has a saved report in the selected date range."
      />
    @else
      <x-ui.table>
        <x-slot:head>
          <tr>
            <th>Student</th>
            <th>Current Batch</th>
            <th>Coach</th>
            <th>Country</th>
            <th>Status</th>
            <th class="text-right">Action</th>
          </tr>
        </x-slot:head>

        @foreach($students as $student)
          @php
            $displayGroups = $student->groups->where('is_active', true);
            if ($displayGroups->isEmpty()) {
                $displayGroups = $student->groups;
            }
            $reportUrl = route($routePrefix.'.reports.students.show', array_filter([
                'student' => $student,
                'date_from' => $dateFrom,
                'date_to' => $dateTo,
            ], fn ($value) => $value !== ''));
          @endphp
          <tr>
            <td>
              <div class="grid gap-1">
                <div class="font-semibold text-slate-900">{{ $student->name }}</div>
                <div class="text-xs font-medium text-slate-500">{{ $student->username }}</div>
              </div>
            </td>
            <td>{{ $displayGroups->pluck('name')->filter()->unique()->join(', ') ?: '—' }}</td>
            <td>{{ $displayGroups->pluck('coach.name')->filter()->unique()->join(', ') ?: '—' }}</td>
            <td>{{ \App\Models\User::studentCountryLabel($student->country) }}</td>
            <td><x-ui.badge label="Need Assessment" variant="warning" /></td>
            <td class="text-right"><x-ui.button :href="$reportUrl" size="sm">Create Report</x-ui.button></td>
          </tr>
        @endforeach
      </x-ui.table>

      <div class="pt-4">
        {{ $students->links('components.ui.pagination') }}
      </div>
    @endif
  @endif
</div>
